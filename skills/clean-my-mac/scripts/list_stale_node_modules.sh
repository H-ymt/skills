#!/usr/bin/env bash
# clean-my-mac: list_stale_node_modules.sh
# Lists top-level node_modules directories with the project's last activity,
# oldest first, and prints removal commands for the stale ones. LIST ONLY:
# it never deletes. Nested node_modules and anything under a hidden directory
# (.next, .open-next, ...) are skipped.
#
# Last activity = date of the last git commit; for a project without git, the
# modification date of its package.json. Stale = older than --days (default 30).
#
# Usage: bash list_stale_node_modules.sh [--days N] [root ...]   (default root: $HOME)

set -euo pipefail

DAYS=30
ROOTS=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --days) DAYS="${2:?--days needs a number}"; shift 2 ;;
    -*) echo "unknown option: $1" >&2; exit 2 ;;
    *) ROOTS+=("$1"); shift ;;
  esac
done
[[ ${#ROOTS[@]} -gt 0 ]] || ROOTS=("$HOME")

CUTOFF=$(date -v-"${DAYS}"d +%F)

human_size() { # KB
  awk -v k="$1" 'BEGIN {
    if (k >= 1048576) printf "%.1fG", k / 1048576;
    else if (k >= 1024) printf "%.0fM", k / 1024;
    else printf "%dK", k
  }'
}

rows=""
while IFS= read -r nm; do
  [[ -n "$nm" ]] || continue
  project=$(dirname "$nm")
  last=$(git -C "$project" log -1 --format=%cs 2>/dev/null) || last=""
  if [[ -z "$last" ]]; then
    last=$(stat -f %Sm -t %F "$project/package.json" 2>/dev/null) || last="unknown"
  fi
  kb=$(du -sk "$nm" 2>/dev/null | cut -f1)
  status="-"
  [[ "$last" != "unknown" && "$last" < "$CUTOFF" ]] && status="STALE"
  rows+="$last|$kb|$status|$nm"$'\n'
done < <(find "${ROOTS[@]}" \
  \( -name '.*' ! -name . \) -prune -o \
  -path "$HOME/Library" -prune -o \
  -name node_modules -type d -print -prune 2>/dev/null)

if [[ -z "$rows" ]]; then
  echo "No node_modules found."
  exit 0
fi

printf "%-8s %-12s %-6s %s\n" "SIZE" "LAST ACTIVITY" "STATUS" "PATH"
stale_kb=0
stale_cmds=""
while IFS='|' read -r last kb status nm; do
  printf "%-8s %-12s %-6s %s\n" "$(human_size "$kb")" "$last" "$status" "$nm"
  if [[ "$status" == "STALE" ]]; then
    stale_kb=$((stale_kb + kb))
    stale_cmds+="rm -rf -- \"$nm\""$'\n'
  fi
done < <(printf '%s' "$rows" | sort -t'|' -k1,1)

echo ""
if [[ -z "$stale_cmds" ]]; then
  echo "Nothing older than $DAYS days."
else
  echo "STALE (older than $DAYS days): $(human_size "$stale_kb"). Review, drop any project you still use, then run:"
  printf '%s' "$stale_cmds"
fi
